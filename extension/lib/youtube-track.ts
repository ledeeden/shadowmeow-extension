import type { CaptionTrack } from '@shadow-language/contracts';

export type YoutubeCaptionTrackLike = {
  id?: string;
  vssId?: string;
  language?: string;
  languageCode?: string;
  kind?: string;
  baseUrl?: string;
};

function trackLanguage(track: YoutubeCaptionTrackLike): string {
  return String(track.languageCode || track.language || '').trim();
}

function trackSourceId(track: YoutubeCaptionTrackLike): string {
  return String(track.vssId || track.id || '').trim();
}

function isEnglishLanguage(value: string): boolean {
  return /^en(?:-|$)/i.test(value);
}

function hasEnglishSourceId(value: string): boolean {
  return /(?:^|[.])en(?:-|$)/i.test(value);
}

function hasAutoGeneratedMarker(track: YoutubeCaptionTrackLike): boolean {
  if (String(track.kind || '').trim().toLowerCase() === 'asr') return true;
  const sourceId = trackSourceId(track).toLowerCase();
  if (/^a(?:[.]|$)/.test(sourceId)) return true;
  try {
    return new URL(track.baseUrl || '').searchParams.get('kind')?.toLowerCase() === 'asr';
  } catch {
    return false;
  }
}

export function isEnglishCaptionTrack(track: Pick<CaptionTrack, 'id' | 'language' | 'kind'> | YoutubeCaptionTrackLike): boolean {
  if (track.kind === 'translation') return false;
  return isEnglishLanguage(trackLanguage(track)) || hasEnglishSourceId(trackSourceId(track));
}

export function classifyYoutubeCaptionTrack(track: YoutubeCaptionTrackLike): CaptionTrack['kind'] {
  if (!isEnglishCaptionTrack(track)) return 'translation';
  return hasAutoGeneratedMarker(track) ? 'asr' : 'manual';
}

function trackRank(track: CaptionTrack): [number, number] {
  // Auto-generated JSON3 tracks commonly carry the per-word offsets needed
  // for an honest word-level timeline. A manual track remains the fallback.
  const kindRank = track.kind === 'asr' ? 0 : 1;
  const languageRank = track.language.toLowerCase() === 'en' ? 0 : 1;
  return [kindRank, languageRank];
}

export function sortEnglishCaptionTracks(tracks: CaptionTrack[]): CaptionTrack[] {
  return tracks
    .map((track, index) => ({ track, index }))
    .filter(({ track }) => isEnglishCaptionTrack(track))
    .sort((left, right) => {
      const [leftKind, leftLanguage] = trackRank(left.track);
      const [rightKind, rightLanguage] = trackRank(right.track);
      return leftKind - rightKind || leftLanguage - rightLanguage || left.index - right.index;
    })
    .map(({ track }) => track);
}

export function chooseEnglishCaptionTrack(tracks: CaptionTrack[]): CaptionTrack | null {
  return sortEnglishCaptionTracks(tracks)[0] || null;
}
