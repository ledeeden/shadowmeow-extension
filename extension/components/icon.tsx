export type IconName = keyof typeof icons;

/** Decorative icons inherit text color; interactive labels belong on the control. */
export function Icon({ name, size = '1.15em', className = '' }: { name: IconName; size?: number | string; className?: string }) {
  const Component = icons[name];
  return <Component aria-hidden="true" focusable="false" size={size} strokeWidth={1.8} className={`sl-icon ${className}`} style={{ display: 'inline-block', flexShrink: 0, verticalAlign: '-0.18em' }} />;
}
